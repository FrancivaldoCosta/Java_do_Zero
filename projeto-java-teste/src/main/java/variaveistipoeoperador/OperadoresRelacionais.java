package variaveistipoeoperador;

public class OperadoresRelacionais {
	
	public static void main(String[] args) {
		
		
		int num1 = 10;
		int num2 = 5;

		if (num1 == num2) {
			System.out.println("TRUE -> Método a ser executado porque deu true na condição");
		} else {
			System.out.println("FALSE -> Método a ser executado porque deu false na condição");
		}
			
		int idade = 18;
		
		if (idade >= 18) {
			System.out.println("Pode faze carteira de motorista");
		} else {
			System.out.println("Não pode ter carteira de motorista");
		}
		
	}

}
