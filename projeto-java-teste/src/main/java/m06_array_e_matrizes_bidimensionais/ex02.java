package m06_array_e_matrizes_bidimensionais;

public class ex02 {
	
	public static void main(String[] args) {
		
		int[] numeros2 = new int[4];
		numeros2[0] = 50;
		numeros2[1] = 40;
		numeros2[2] = 66;
		numeros2[3] = 75;
		
		System.out.println("Valor atual: " + numeros2[2]);
		
		numeros2[2] = 86; /* Valor de troca, atribuição de valor */
		
		System.out.println("Valor trocado: " + numeros2[2]);		
	}
	
	

}
