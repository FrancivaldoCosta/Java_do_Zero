package m01_classe_main;

public class ClasseTipoDado {
	
	public static void main(String[] args) {
		
		/* Representação de idade em número inteiro. */
		int idade = 38;
		
		/* Representação da idade em fração */
		double idadeMesesMaternidade = 2.6;
		
		/* Representa valores de sim = true, e não = false */
		boolean usuarioAtivo = true;
		
		/* Representa textos */
		String nome = "Alex Fernando Egidio";
		
		/* Representado por uma letra, que define o tipo de algo no mundo real */
		char sexoPessoa = 'M';
		
		
		System.out.println("Idade: " + idade);
		System.out.println("Idade maternidade: " + idadeMesesMaternidade);
		System.out.println("Usuário ativo: " + usuarioAtivo);
		System.out.println("Nome da pessoa: " + nome);
		System.out.println("Sexo da pessoa: " + sexoPessoa);
		
	}

}
